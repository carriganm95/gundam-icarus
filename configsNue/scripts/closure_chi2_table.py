#!/usr/bin/env python3
"""Table of the GUNDAM-vs-CAF-truth closure chi2 for every fake-data study.

Finds data/<var>/<version>/<study>/xsec_<tag>.root and recomputes the same
chi2 that makePrettyPlots.py draws on genie_gundam_xsec_comparison.png
(makePrettyPlots.closure_chi2, with the tag's registered truth reweight).
Writes one table per variable and version to
plots/<var>/<version>/closure_chi2_table.{png,md,csv}.

  python3 scripts/closure_chi2_table.py                      # everything found
  python3 scripts/closure_chi2_table.py --versions v31p2 v31p2_noG4
  python3 scripts/closure_chi2_table.py --vars EleAngle --versions v31p2
"""
import argparse
import csv
import glob
import os
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, HERE)
import analysis_vars  # noqa: E402
import makePrettyPlots as mpp  # noqa: E402

TAG_ORDER = ["asimov", "emb", "gainHigh", "gainLow", "nc", "pAngle", "Q2", "res0p5", "res1p5",
             "QE0p5", "QE1p5", "MEC0p5", "MEC1p5", "DIS0p5", "DIS1p5"]
FAKE_TAGS = set(mpp.TRUTH_REWEIGHTS) - {"10pct", "asimovGrid"}


def find_runs(data_dir, variables, versions):
    """Yield (var, version, study_dir_name, tag, xsec_path)."""
    for var in variables:
        for path in sorted(glob.glob(f"{data_dir}/{var}/*/*/xsec_*.root")):
            study_dir = os.path.dirname(path)
            version = os.path.basename(os.path.dirname(study_dir))
            tag = os.path.basename(path)[len("xsec_"):-len(".root")]
            if tag not in FAKE_TAGS or (versions and version not in versions):
                continue
            yield var, version, os.path.basename(study_dir), tag, path


def sort_key(row):
    t = row["tag"]
    return (row["var"], row["version"], TAG_ORDER.index(t) if t in TAG_ORDER else 99, row["study"])


def fmt(x, spec):
    return "—" if x is None else format(x, spec)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--data-dir", default=f"{HERE}/data")
    p.add_argument("--vars", nargs="+", default=["EleE", "EleAngle"])
    p.add_argument("--versions", nargs="+", default=None,
                   help="version dirs to include, e.g. v31 v31p2 (default: all)")
    p.add_argument("--plots-dir", default=f"{HERE}/plots",
                   help="tables go to <plots-dir>/<var>/<version>/closure_chi2_table.{png,md,csv}")
    args = p.parse_args()

    rows = []
    for var, version, study, tag, path in find_runs(args.data_dir, args.vars, args.versions):
        analysis_vars.set_var(var)
        try:
            res = mpp.closure_chi2(path, mpp.TRUTH_REWEIGHTS[tag])
        except Exception as e:  # e.g. a run still writing its file
            print(f"skip {path}: {e}", file=sys.stderr)
            continue
        rows.append(dict(var=var, version=version, study=study, tag=tag, **res))
    rows.sort(key=sort_key)
    if not rows:
        sys.exit("no xsec files found")

    groups = {}
    for r_ in rows:
        groups.setdefault((r_["var"], r_["version"]), []).append(r_)
    for (var, version), grp in groups.items():
        out = f"{args.plots_dir}/{var}/{version}/closure_chi2_table"
        write_table(grp, var, version, out)
        print(f"Wrote {out}.png/.md/.csv")


def table_cells(r_):
    """Study, corr chi2/ndof, p, uncorr chi2/ndof, p as display strings."""
    n = r_["ndof"]
    corr = "—" if r_["chi2_corr"] is None else f"{r_['chi2_corr']:.1f}/{n} = {r_['chi2_corr'] / n:.2f}"
    return [r_["study"], corr, fmt(r_["p_corr"], ".3f"),
            f"{r_['chi2_uncorr']:.1f}/{n} = {r_['chi2_uncorr'] / n:.2f}", fmt(r_["p_uncorr"], ".3f")]


HEADER = ["Study", "χ²/ndof (corr)", "p (corr)", "χ²/ndof (uncorr)", "p (uncorr)"]


def write_table(rows, var, version, out):
    """One variable+version: PNG (p < 0.05 shaded red), Markdown and CSV."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    os.makedirs(os.path.dirname(out), exist_ok=True)
    cells = [table_cells(r_) for r_ in rows]
    title = f"GUNDAM vs CAF truth closure χ² — {var} {version}"

    with open(out + ".md", "w") as f:
        f.write(f"# {title}\n\nGenerated by `scripts/closure_chi2_table.py`. Correlated χ² uses the "
                "full calcXsec covariance; the truth reference includes each tag's truth reweight.\n\n"
                "| " + " | ".join(HEADER) + " |\n|" + "---|" * len(HEADER) + "\n"
                + "".join("| " + " | ".join(c) + " |\n" for c in cells))
    with open(out + ".csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["study", "tag", "ndof", "chi2_corr", "p_corr",
                                          "chi2_uncorr", "p_uncorr"])
        w.writeheader()
        for r_ in rows:
            w.writerow({k: r_[k] for k in w.fieldnames})

    bad = lambda p: p is not None and p < 0.05  # noqa: E731
    shade = lambda p: "#f4cccc" if bad(p) else "white"  # noqa: E731
    colors = [["white", shade(r_["p_corr"]), shade(r_["p_corr"]),
               shade(r_["p_uncorr"]), shade(r_["p_uncorr"])] for r_ in rows]
    fig, ax = plt.subplots(figsize=(9, 0.255 * (len(cells) + 2)))
    ax.axis("off")
    tab = ax.table(cellText=cells, colLabels=HEADER, cellColours=colors,
                   colColours=["#d9d9d9"] * len(HEADER), loc="upper center", cellLoc="center")
    tab.auto_set_font_size(False)
    tab.set_fontsize(10)
    tab.scale(1, 1.3)
    for (row, _), cell in tab.get_celld().items():
        if row == 0:
            cell.set_text_props(weight="bold")
    ax.set_title(title, fontsize=12, pad=8)
    fig.savefig(out + ".png", dpi=150, bbox_inches="tight")
    plt.close(fig)


if __name__ == "__main__":
    main()
